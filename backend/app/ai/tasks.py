"""AI-assisted product tasks. Outputs are advisory and stored apart from deterministic facts."""

import json
import uuid
from typing import Any

from sqlalchemy.orm import Session

from app.agents.registry import agent_run
from app.ai.service import run_json_task
from app.domain import Category, Engine, Origin, values
from app.models import ArchitectureSnapshot, Finding, ProjectVersion, TestCase, TestPlan

_SYSTEM = (
    "You are a senior software quality engineer. Use only the facts provided. If the facts are insufficient, "
    "say so. Reply with JSON matching the schema."
)


def _schema(properties: dict[str, Any]) -> dict[str, Any]:
    return {
        "type": "object",
        "properties": properties,
        "required": list(properties),
        "additionalProperties": False,
    }


def explain_finding(db: Session, finding_id: uuid.UUID, job_id: uuid.UUID | None = None) -> None:
    finding = db.get_one(Finding, finding_id)
    facts = {"title": finding.title, "category": finding.category, "severity": finding.severity,
             "description": finding.description[:3000], "component": finding.affected_component,
             "facts": json.dumps(finding.facts)[:3000]}  # fmt: skip
    with agent_run(db, "bug_investigator", project_id=finding.project_id, job_id=job_id, finding=str(finding.id)) as out:
        result = run_json_task(
            db, task_type="explain", system=_SYSTEM, project_id=finding.project_id,
            prompt="Explain this finding for a developer: likely root cause, user impact, and how to confirm it.\n\n"
                   + json.dumps(facts, indent=2),
            schema=_schema({"root_cause": {"type": "string"}, "impact": {"type": "string"}, "how_to_confirm": {"type": "string"}}),
        )  # fmt: skip
        data = result.data
        finding.ai_explanation = (
            f"[AI-generated by {result.label} - advisory, not verified]\n\n"
            f"Likely root cause: {data['root_cause']}\n\nImpact: {data['impact']}\n\nHow to confirm: {data['how_to_confirm']}"
        )
        out.update(model=result.label, latency_ms=result.latency_ms)
    db.commit()


def summarise_architecture(db: Session, version_id: uuid.UUID, job_id: uuid.UUID | None = None) -> None:
    version = db.get_one(ProjectVersion, version_id)
    snapshot: ArchitectureSnapshot | None = version.snapshot
    if snapshot is None:
        return
    inventory = {k: snapshot.inventory.get(k) for k in (
        "languages", "frameworks", "package_managers", "test_frameworks", "monorepo", "openapi_specs", "migrations")}  # fmt: skip
    inventory["components"] = [{"name": c.name, "kind": c.kind, "path": c.path, "frameworks": c.frameworks}
                               for c in snapshot.components[:30]]  # fmt: skip
    inventory["endpoint_count"] = len(snapshot.api_endpoints)
    inventory["data_models"] = len(snapshot.inventory.get("data_models") or [])
    with agent_run(db, "architecture_analyst", project_id=version.project_id, job_id=job_id, version=str(version.id)) as out:
        result = run_json_task(
            db, task_type="summarize", system=_SYSTEM, project_id=version.project_id,
            prompt="Summarise this project's architecture in at most 150 words and list up to five quality risks "
                   "that follow directly from the inventory.\n\n" + json.dumps(inventory, indent=2, default=str)[:8000],
            schema=_schema({"summary": {"type": "string"}, "risks": {"type": "array", "items": {"type": "string"}}}),
        )  # fmt: skip
        risks = "\n".join(f"- {risk}" for risk in result.data["risks"][:5])
        snapshot.ai_summary = f"{result.data['summary']}\n\nRisks suggested by the model:\n{risks}"
        snapshot.ai_model = result.label
        out.update(model=result.label, latency_ms=result.latency_ms)
    db.commit()


def suggest_test_cases(db: Session, plan_id: uuid.UUID, job_id: uuid.UUID | None = None) -> None:
    """Adds AI-suggested cases as MANUAL: they are ideas, never executed or reported as passed."""
    plan = db.get_one(TestPlan, plan_id)
    snapshot = db.get_one(ProjectVersion, plan.version_id).snapshot
    context = {
        "frameworks": (snapshot.inventory.get("frameworks") if snapshot else []) or [],
        "endpoints": [f"{e.method} {e.path}" for e in (snapshot.api_endpoints if snapshot else [])][:40],
        "routes": [r.path for r in (snapshot.routes if snapshot else [])][:40],
        "already_planned": [c.title for c in plan.cases][:60],
    }
    categories = values(Category)
    with agent_run(db, "qa_planner", project_id=plan.project_id, job_id=job_id, plan=str(plan.id), mode="ai_suggestions") as out:
        result = run_json_task(
            db, task_type="test_suggestions", system=_SYSTEM, project_id=plan.project_id,
            prompt="Suggest up to six additional test cases that are NOT already planned. Be specific to the "
                   "endpoints and routes listed.\n\n" + json.dumps(context, indent=2),
            schema=_schema({"cases": {"type": "array", "items": _schema({
                "title": {"type": "string"}, "category": {"type": "string", "enum": categories},
                "steps": {"type": "array", "items": {"type": "string"}}})}}),
        )  # fmt: skip
        existing = sum(1 for c in plan.cases if c.origin == Origin.AI_SUGGESTED.value)
        added = 0
        for index, case in enumerate(result.data["cases"][:6], start=existing + 1):
            plan.cases.append(TestCase(
                key=f"AI-{index:03d}", title=str(case["title"])[:300], category=case["category"],
                engine=Engine.MANUAL.value, origin=Origin.AI_SUGGESTED.value, priority=3,
                spec={"steps": [str(s)[:300] for s in case["steps"][:10]], "suggested_by": result.label,
                      "reason": "AI-suggested idea; not automated, requires manual execution."},
            ))  # fmt: skip
            added += 1
        out.update(model=result.label, added=added)
    db.commit()
