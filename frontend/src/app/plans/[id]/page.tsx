"use client";

import { useQuery } from "@tanstack/react-query";
import { useParams, useRouter } from "next/navigation";

import { QueryView, useAction } from "@/components/query";
import { Badge, Button, Card, ErrorNote, Notice, PageHeader, StateBadge, Table } from "@/components/ui";
import { api, formatDate } from "@/lib/api";
import type { PlanReadiness, TestCase, TestPlan, TestRun } from "@/lib/types";

export default function PlanPage() {
  const { id } = useParams<{ id: string }>();
  const router = useRouter();
  const plan = useQuery({ queryKey: ["plan", id], queryFn: () => api<TestPlan>(`/plans/${id}`) });
  // Readiness is computed on demand by the backend (tool, target, device and credential checks); nothing is executed.
  const readiness = useQuery({ queryKey: ["plan-readiness", id], queryFn: () => api<PlanReadiness>(`/plans/${id}/readiness`), staleTime: 0 });
  const toggle = useAction<{ caseId: string; enabled: boolean }, TestCase>("PATCH", ({ caseId }) => `/plans/${id}/cases/${caseId}`);
  const start = useAction<void, TestRun>("POST", `/plans/${id}/runs`);
  const suggest = useAction("POST", `/plans/${id}/suggestions`);

  return (
    <QueryView query={plan}>
      {(data) => {
        const cases = data.cases ?? [];
        const enabled = cases.filter((c) => c.enabled).length;
        const reports = readiness.data?.cases ?? {};
        const summary = readiness.data?.summary ?? {};
        const notReady = Object.entries(summary).filter(([status]) => status !== "ready" && status !== "not_applicable");
        return (
          <>
            <PageHeader
              title={data.name}
              description={`${enabled} of ${cases.length} cases enabled · target: ${data.target_url ?? "none (static analysis only)"}`}
              actions={
                <>
                  <Button disabled={readiness.isFetching} onClick={() => void readiness.refetch()}>
                    {readiness.isFetching ? "Checking readiness…" : "Re-check readiness"}
                  </Button>
                  <Button disabled={suggest.isPending || suggest.isSuccess} onClick={() => suggest.mutate()}>
                    {suggest.isSuccess ? "Suggestions queued" : "Suggest cases (local AI)"}
                  </Button>
                  <Button variant="primary" disabled={start.isPending || enabled === 0} onClick={() => start.mutate(undefined, { onSuccess: (run) => router.push(`/runs/${run.id}`) })}>
                    {start.isPending ? "Starting…" : "Start test run"}
                  </Button>
                </>
              }
            />
            <div className="space-y-4">
              {start.isError && <ErrorNote error={start.error} />}
              {suggest.isError && <ErrorNote error={suggest.error} />}
              {toggle.isError && <ErrorNote error={toggle.error} />}
              {readiness.isError && <ErrorNote error={readiness.error} retry={() => void readiness.refetch()} />}
              {suggest.isSuccess && <Notice>AI suggestions are being generated by the worker. They appear below as manual, AI-suggested cases; reload in a moment.</Notice>}
              {data.allow_mutations && <Notice tone="warn">State-changing API requests are enabled for this plan.</Notice>}
              <Card title="Test readiness">
                {readiness.isPending ? (
                  <p className="text-muted">Checking tools, target, devices and credentials…</p>
                ) : (
                  <div className="space-y-2">
                    <ul className="flex flex-wrap gap-2">
                      {Object.entries(summary).map(([status, count]) => (
                        <li key={status}>
                          <StateBadge state={status} /> <span className="tabular-nums">{count}</span>
                        </li>
                      ))}
                    </ul>
                    <p className="text-muted">
                      {notReady.length === 0
                        ? "Every automated case can run now."
                        : "Cases that are not ready will be recorded as blocked with the reason shown in the table below. They are never counted as passed."}
                      {readiness.data ? ` Checked ${formatDate(readiness.data.checked_at)}.` : ""}
                    </p>
                  </div>
                )}
              </Card>
              <Card title={`Cases (${cases.length})`}>
                <Table label="Test cases" head={["Run", "Key", "Case", "Category", "Engine", "Readiness"]}>
                  {cases.map((testCase) => {
                    const report = reports[testCase.key];
                    return (
                      <tr key={testCase.id} className={testCase.enabled ? undefined : "opacity-60"}>
                        <td>
                          <input
                            type="checkbox"
                            aria-label={`Include ${testCase.key} in runs`}
                            checked={testCase.enabled}
                            disabled={toggle.isPending}
                            onChange={(event) => toggle.mutate({ caseId: testCase.id, enabled: event.target.checked })}
                          />
                        </td>
                        <td className="font-mono text-xs whitespace-nowrap">{testCase.key}</td>
                        <td>
                          {testCase.title} {testCase.origin === "ai_suggested" && <Badge tone="warn">AI suggested</Badge>}
                          {testCase.engine === "manual" && <span className="block text-xs text-muted">{String(testCase.spec.reason ?? "Manual review")}</span>}
                        </td>
                        <td><Badge>{testCase.category}</Badge></td>
                        <td className="text-muted">{testCase.engine.replaceAll("_", " ")}</td>
                        <td className="max-w-sm">
                          {testCase.engine === "manual" ? (
                            <span className="text-muted">manual: not tested</span>
                          ) : report ? (
                            <>
                              <StateBadge state={report.status} />
                              {report.reasons.map((reason) => (
                                <span key={reason} className="mt-0.5 block text-xs text-muted">{reason}</span>
                              ))}
                            </>
                          ) : (
                            <span className="text-muted">{testCase.enabled ? "…" : "disabled"}</span>
                          )}
                        </td>
                      </tr>
                    );
                  })}
                </Table>
              </Card>
              {data.notes.length > 0 && (
                <Card title="What this plan does not cover">
                  <ul className="list-disc space-y-1 pl-5 text-muted">
                    {data.notes.map((note) => (
                      <li key={note}>{note}</li>
                    ))}
                  </ul>
                </Card>
              )}
            </div>
          </>
        );
      }}
    </QueryView>
  );
}
