"use client";

import { useQuery } from "@tanstack/react-query";
import { useParams } from "next/navigation";
import type { ReactNode } from "react";

import { QueryView, useAction } from "@/components/query";
import { Badge, Button, Card, ErrorNote, LinkButton, Notice, PageHeader, Table } from "@/components/ui";
import { api, formatBytes } from "@/lib/api";
import type { Architecture } from "@/lib/types";

function Tags({ items, empty = "none detected" }: { items: string[] | undefined; empty?: string }) {
  if (!items?.length) return <span className="text-muted">{empty}</span>;
  return (
    <span className="flex flex-wrap gap-1">
      {items.map((item) => (
        <Badge key={item} tone="info">{item}</Badge>
      ))}
    </span>
  );
}

function Fact({ label, children }: { label: string; children: ReactNode }) {
  return (
    <>
      <dt className="text-muted">{label}</dt>
      <dd>{children}</dd>
    </>
  );
}

export default function ArchitecturePage() {
  const { id } = useParams<{ id: string }>();
  const architecture = useQuery({ queryKey: ["architecture", id], queryFn: () => api<Architecture>(`/projects/${id}/architecture`) });
  const summarise = useAction("POST", `/projects/${id}/architecture/summary`);

  return (
    <>
      <PageHeader
        title="Architecture inventory"
        description="Facts extracted deterministically from the imported files. The optional AI narrative is shown separately and is not evidence."
        actions={<LinkButton href={`/projects/${id}`}>Back to project</LinkButton>}
      />
      <QueryView query={architecture}>
        {(data) => {
          const inv = data.inventory;
          return (
            <div className="space-y-4">
              {data.unsupported.length > 0 && (
                <Notice tone="warn">
                  <p className="font-medium">Not supported or not analysed</p>
                  <ul className="mt-1 list-disc pl-5">
                    {data.unsupported.map((item) => (
                      <li key={item}>{item}</li>
                    ))}
                  </ul>
                </Notice>
              )}
              <div className="grid gap-4 lg:grid-cols-2">
                <Card title={`Detected stack (version ${data.version.number})`}>
                  <dl className="grid grid-cols-[9rem_1fr] gap-y-2">
                    <Fact label="Languages">
                      {inv.languages?.length ? (
                        <ul>
                          {inv.languages.map((lang) => (
                            <li key={lang.name}>{lang.name} <span className="text-muted">· {lang.files} files · {formatBytes(lang.bytes)}</span></li>
                          ))}
                        </ul>
                      ) : (
                        <span className="text-muted">none detected</span>
                      )}
                    </Fact>
                    <Fact label="Frameworks"><Tags items={inv.frameworks} /></Fact>
                    <Fact label="Package managers"><Tags items={inv.package_managers} /></Fact>
                    <Fact label="Test frameworks"><Tags items={inv.test_frameworks} /></Fact>
                    <Fact label="Test files">{inv.test_files?.count ?? 0} <span className="text-muted">(coverage % is not measured)</span></Fact>
                    <Fact label="Monorepo">{inv.monorepo?.detected ? `yes (${inv.monorepo.package_count} packages)` : "no"}</Fact>
                    <Fact label="Migrations"><Tags items={inv.migrations} /></Fact>
                    <Fact label="Containers"><Tags items={[...(inv.containers?.dockerfiles ?? []), ...(inv.containers?.compose_services ?? []).map((s) => `service: ${s.name}`)]} /></Fact>
                    <Fact label="CI"><Tags items={inv.ci} /></Fact>
                  </dl>
                </Card>
                <Card
                  title="AI summary (advisory)"
                  action={
                    <Button disabled={summarise.isPending || summarise.isSuccess} onClick={() => summarise.mutate()}>
                      {summarise.isSuccess ? "Queued - refresh shortly" : data.ai_summary ? "Regenerate" : "Generate with local model"}
                    </Button>
                  }
                >
                  {summarise.isError && <ErrorNote error={summarise.error} />}
                  {data.ai_summary ? (
                    <>
                      <p className="whitespace-pre-wrap">{data.ai_summary}</p>
                      <p className="mt-2 text-xs text-muted">Generated by {data.ai_model}. Not verified.</p>
                    </>
                  ) : (
                    <p className="text-muted">No summary generated. It is optional and runs on the local model.</p>
                  )}
                </Card>
              </div>
              <Card title={`Components (${data.components.length})`}>
                {data.components.length === 0 ? (
                  <p className="text-muted">No dependency manifest was recognised.</p>
                ) : (
                  <Table label="Components" head={["Name", "Kind", "Path", "Frameworks", "Manifest", "Dependencies"]}>
                    {data.components.map((component) => (
                      <tr key={`${component.path}:${component.name}`}>
                        <td className="font-medium">{component.name}</td>
                        <td><Badge>{component.kind}</Badge></td>
                        <td className="font-mono text-xs">{component.path || "."}</td>
                        <td><Tags items={component.frameworks} empty="-" /></td>
                        <td className="text-muted">{component.details.manifest} ({component.details.package_manager})</td>
                        <td className="tabular-nums">{component.details.dependencies?.length ?? "-"}</td>
                      </tr>
                    ))}
                  </Table>
                )}
              </Card>
              <div className="grid gap-4 lg:grid-cols-2">
                <Card title={`API endpoints (${data.api_endpoints.length})`}>
                  {data.api_endpoints.length === 0 ? (
                    <p className="text-muted">No endpoints found in code or specifications.</p>
                  ) : (
                    <Table label="API endpoints" head={["Method", "Path", "Found in", "File"]}>
                      {data.api_endpoints.map((endpoint) => (
                        <tr key={`${endpoint.method}${endpoint.path}${endpoint.origin}${endpoint.source_file}`}>
                          <td><Badge tone="info">{endpoint.method}</Badge></td>
                          <td className="font-mono text-xs break-all">{endpoint.path}</td>
                          <td>{endpoint.origin}</td>
                          <td className="font-mono text-xs break-all text-muted">{endpoint.source_file}</td>
                        </tr>
                      ))}
                    </Table>
                  )}
                </Card>
                <div className="space-y-4">
                  <Card title={`Frontend routes (${data.routes.length})`}>
                    {data.routes.length === 0 ? (
                      <p className="text-muted">No file-system routes detected (supported: Next.js app and pages routers).</p>
                    ) : (
                      <ul className="space-y-1 font-mono text-xs">
                        {data.routes.map((route) => (
                          <li key={route.source_file}>{route.path} <span className="text-muted">· {route.source_file}</span></li>
                        ))}
                      </ul>
                    )}
                  </Card>
                  <Card title="Configuration">
                    <dl className="grid grid-cols-[9rem_1fr] gap-y-2">
                      <Fact label="Env variable names"><Tags items={inv.env_var_names} /></Fact>
                      <Fact label="Data models"><Tags items={inv.data_models?.map((m) => `${m.name} (${m.kind})`)} /></Fact>
                      <Fact label="Sensitive files">
                        {inv.security_sensitive_files?.length ? (
                          <ul className="font-mono text-xs">
                            {inv.security_sensitive_files.slice(0, 15).map((file) => (
                              <li key={file}>{file}</li>
                            ))}
                          </ul>
                        ) : (
                          <span className="text-muted">none flagged</span>
                        )}
                      </Fact>
                    </dl>
                  </Card>
                </div>
              </div>
              {inv.analysis_notes?.length ? (
                <Card title="How to read this inventory">
                  <ul className="list-disc space-y-1 pl-5 text-muted">
                    {inv.analysis_notes.map((note) => (
                      <li key={note}>{note}</li>
                    ))}
                  </ul>
                </Card>
              ) : null}
            </div>
          );
        }}
      </QueryView>
    </>
  );
}
